#!/usr/bin/env python3
"""BerryAPI IDL code generator.

Reads api/berry.idl and emits, from that one description:

  include/berry/generated_bindings.h   C++ binding table + typed helpers
  generated/berry.d.ts                 TypeScript definitions (autocomplete)
  generated/berry.luau                 Luau type definitions
  docs/API.md                          reference documentation

The generated C++ header is included by the runtime so the binding names, their
capabilities and their arities cannot drift from the documented API. Run
`make idl` to regenerate and `make idl-check` to fail when outputs are stale.

No third-party dependencies: a small hand-written parser keeps this runnable
from a plain `python3` on a build machine.
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IDL_PATH = os.path.join(ROOT, "api", "berry.idl")

BANNER = "// Generated by tools/idlgen.py from api/berry.idl. DO NOT EDIT."

# IDL type -> (C++ type, TypeScript type, Luau type, doc description)
TYPE_MAP = {
    "nil": ("void", "void", "()", "no value"),
    "bool": ("bool", "boolean", "boolean", "boolean"),
    "number": ("f64", "number", "number", "number"),
    "string": ("std::string", "string", "string", "string"),
    "Actor": ("ActorHandle", "ActorHandle", "ActorHandle", "actor handle"),
    "Vec3": ("Vec3", "Vec3", "Vec3", "3-component vector"),
    "Rgba": ("Rgba", "Rgba", "Rgba", "RGBA colour"),
    "Widget": ("WidgetId", "WidgetId", "WidgetId", "HUD widget handle"),
    "Task": ("u64", "TaskId", "TaskId", "async task id"),
    "HttpResult": ("HttpResult", "HttpResult", "HttpResult", "HTTP response"),
}


class IdlError(Exception):
    pass


# IDL capability name -> CapKind enum value. Kept explicit so a typo in the IDL
# fails the build instead of silently mapping to CapKind::Unknown (which would
# make the runtime treat the binding as capability-free).
CAPABILITY_ENUM = {
    "combat": "CapKind::Combat",
    "render": "CapKind::Render",
    "world": "CapKind::World",
    "network": "CapKind::Network",
    "fileio": "CapKind::FileIO",
    "hud": "CapKind::Hud",
    "perf": "CapKind::Perf",
    "input": "CapKind::Input",
    "events": "CapKind::Events",
    "audio": "CapKind::Audio",
    "cosmetic": "CapKind::Cosmetic",
}


class Param:
    def __init__(self, name, typ):
        self.name = name
        self.type = typ

    def cpp(self):
        return TYPE_MAP[self.type][0]

    def ts(self):
        return TYPE_MAP[self.type][1]

    def luau(self):
        return TYPE_MAP[self.type][2]


class Function:
    def __init__(self, name, params, ret, capability, doc, module):
        self.name = name
        self.params = params
        self.ret = ret
        self.capability = capability
        self.doc = doc
        self.module = module

    @property
    def binding(self):
        """Canonical binding name, e.g. combat.recent_kills."""
        return "%s.%s" % (self.module.lower(), self.name)


class Event:
    def __init__(self, name, params, doc, module):
        self.name = name
        self.params = params
        self.doc = doc
        self.module = module

    @property
    def channel(self):
        return self.name


class Module:
    def __init__(self, name):
        self.name = name
        self.capability = None
        self.doc = ""
        self.functions = []
        self.events = []


def _split_types(text):
    """Split a parameter list on commas that are not inside < > or ( )."""
    out, depth, cur = [], 0, ""
    for ch in text:
        if ch in "<(":
            depth += 1
        elif ch in ">)":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return [p.strip() for p in out if p.strip()]


def _check_type(typ, where):
    if typ not in TYPE_MAP:
        raise IdlError("unknown type %r in %s" % (typ, where))


def parse(text):
    modules = []
    current = None
    pending_doc = None
    pending_cap = None
    seen_fns = set()
    seen_events = set()

    for lineno, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        try:
            if line.startswith("module "):
                m = re.match(r"module\s+([A-Za-z_][A-Za-z0-9_]*)\s*\{", line)
                if not m:
                    raise IdlError("bad module declaration")
                current = Module(m.group(1))
                modules.append(current)
                pending_doc = None
                pending_cap = None
            elif line == "}":
                current = None
            elif line.startswith("capability "):
                cap = line.split(None, 1)[1].strip()
                if current is None:
                    raise IdlError("capability outside a module")
                if cap not in CAPABILITY_ENUM:
                    raise IdlError("unknown capability %r" % cap)
                current.capability = cap
                pending_cap = cap
            elif line.startswith("doc "):
                pending_doc = _unquote(line.split(None, 1)[1].strip())
            elif line.startswith("fn "):
                if current is None:
                    raise IdlError("fn outside a module")
                fn = _parse_fn(line, current, pending_doc, pending_cap)
                if fn.binding in seen_fns:
                    raise IdlError("duplicate binding %s" % fn.binding)
                seen_fns.add(fn.binding)
                current.functions.append(fn)
                pending_doc = None
            elif line.startswith("event "):
                if current is None:
                    raise IdlError("event outside a module")
                ev = _parse_event(line, current, pending_doc)
                if ev.channel in seen_events:
                    raise IdlError("duplicate event %s" % ev.channel)
                seen_events.add(ev.channel)
                current.events.append(ev)
                pending_doc = None
            else:
                raise IdlError("unrecognised declaration: %r" % line)
        except IdlError as exc:
            raise IdlError("api/berry.idl:%d: %s" % (lineno, exc))
    return modules


def _unquote(s):
    if len(s) >= 2 and s[0] == '"' and s[-1] == '"':
        return s[1:-1]
    return s


def _parse_fn(line, module, doc, cap):
    m = re.match(r"fn\s+([A-Za-z_][A-Za-z0-9_]*)\s*\((.*)\)\s*->\s*(\S+)\s*$", line)
    if not m:
        raise IdlError("bad fn declaration: %r" % line)
    name, argtext, ret = m.group(1), m.group(2), m.group(3)
    params = []
    for arg in _split_types(argtext):
        if ":" not in arg:
            raise IdlError("parameter %r needs a type" % arg)
        pname, ptype = arg.split(":", 1)
        pname, ptype = pname.strip(), ptype.strip()
        _check_type(ptype, "fn %s" % name)
        params.append(Param(pname, ptype))
    _check_type(ret, "fn %s return" % name)
    return Function(name, params, ret, cap or module.capability, doc or "", module.name)


def _parse_event(line, module, doc):
    m = re.match(r"event\s+([A-Za-z_][A-Za-z0-9_]*)\s*\((.*)\)\s*$", line)
    if not m:
        raise IdlError("bad event declaration: %r" % line)
    name, argtext = m.group(1), m.group(2)
    params = []
    for arg in _split_types(argtext):
        if ":" not in arg:
            raise IdlError("event parameter %r needs a type" % arg)
        pname, ptype = arg.split(":", 1)
        pname, ptype = pname.strip(), ptype.strip()
        _check_type(ptype, "event %s" % name)
        params.append(Param(pname, ptype))
    return Event(name, params, doc or "", module.name)


def _capability_enum(cap):
    """Map an IDL capability name to the CapKind enum value."""
    if cap not in CAPABILITY_ENUM:
        raise IdlError("capability %r has no CapKind mapping" % cap)
    return CAPABILITY_ENUM[cap]


#----------------------------------------------------------------------------
# C++ header
#----------------------------------------------------------------------------

def emit_cpp(modules):
    out = [BANNER, "#pragma once", "",
           "#include \"berry/export.h\"",
           "#include \"berry/types.h\"",
           "#include \"berry/manifest.h\"",
           "",
           "#include <string>",
           "",
           "namespace Berry {",
           "namespace api {",
           "",
           "// Capability a generated binding requires. Parsed from the IDL so the",
           "// runtime gate and the documentation share one source of truth.",
           "struct BindingSpec {",
           "  const char* name;",
           "  CapKind capability;",
           "  int arity;",
           "  const char* module;",
           "};",
           ""]
    specs = []
    for mod in modules:
        for fn in mod.functions:
            specs.append((fn.binding, _capability_enum(fn.capability), len(fn.params), mod.name))
    out.append("inline const BindingSpec* BindingSpecs() {")
    out.append("  static const BindingSpec kSpecs[] = {")
    for name, cap, arity, module in specs:
        out.append("      {\"%s\", %s, %d, \"%s\"}," % (name, cap, arity, module))
    out.append("  };")
    out.append("  return kSpecs;")
    out.append("}")
    out.append("")
    out.append("inline size_t BindingSpecCount() { return %d; }" % len(specs))
    out.append("")
    # Lookup by name.
    out.append("/// Returns the spec for `name`, or nullptr when it is not part of")
    out.append("/// the generated API surface.")
    out.append("inline const BindingSpec* FindBindingSpec(const std::string& name) {")
    out.append("  const BindingSpec* specs = BindingSpecs();")
    out.append("  for (size_t i = 0; i < BindingSpecCount(); ++i) {")
    out.append("    if (name == specs[i].name) return &specs[i];")
    out.append("  }")
    out.append("  return nullptr;")
    out.append("}")
    out.append("")
    # Per-module name lists, useful for docs/tests.
    out.append("/// Canonical binding names grouped by module.")
    out.append("struct ModuleBindings {")
    out.append("  const char* module;")
    out.append("  const char* const* names;")
    out.append("  size_t count;")
    out.append("};")
    out.append("")
    for mod in modules:
        if not mod.functions:
            continue
        out.append("inline const char* const k%sNames[] = {" % mod.name)
        for fn in mod.functions:
            out.append("    \"%s\"," % fn.binding)
        out.append("};")
    out.append("")
    mods = [m for m in modules if m.functions]
    out.append("inline const ModuleBindings* ModuleBindingTable() {")
    out.append("  static const ModuleBindings kModules[] = {")
    for mod in mods:
        out.append("      {\"%s\", k%sNames, %d}," % (mod.name, mod.name, len(mod.functions)))
    out.append("  };")
    out.append("  return kModules;")
    out.append("}")
    out.append("")
    out.append("inline size_t ModuleBindingCount() { return %d; }" % len(mods))
    out.append("")
    out.append("}  // namespace api")
    out.append("}  // namespace Berry")
    out.append("")
    return "\n".join(out)


#----------------------------------------------------------------------------
# TypeScript
#----------------------------------------------------------------------------

def _ts_type(t):
    return TYPE_MAP[t][1]


def emit_ts(modules):
    out = [BANNER.replace("//", "//"), "// TypeScript definitions for the BerryAPI script surface.",
           "", "export type TaskId = number;", "export type WidgetId = number;",
           "export interface ActorHandle { id: number; }",
           "export interface Vec3 { x: number; y: number; z: number; }",
           "export interface Rgba { r: number; g: number; b: number; a: number; }",
           "export interface HttpResult { status: number; body: string; ok: boolean; }",
           ""]
    for mod in modules:
        if not mod.functions:
            continue
        out.append("/** Capability required: %s. */" % mod.capability)
        out.append("export interface %s {" % mod.name)
        if mod.doc:
            out.append("  /** %s */" % mod.doc)
        for fn in mod.functions:
            args = ", ".join("%s: %s" % (p.name, _ts_type(p.type)) for p in fn.params)
            ret = "void" if fn.ret == "nil" else _ts_type(fn.ret)
            if fn.doc:
                out.append("  /** %s */" % fn.doc)
            out.append("  %s(%s): %s;" % (fn.name, args, ret))
        out.append("}")
        out.append("")
    # Async facade.
    out.append("/** Coroutine-native async facade (Phase 4). */")
    out.append("export interface AsyncFacade {")
    out.append("  /** Suspend until `ticks` game ticks have elapsed. */")
    out.append("  wait(ticks: number): Promise<void>;")
    out.append("  /** Suspend until `channel` fires; resolves with the payload. */")
    out.append("  eventsOnce(channel: string): Promise<unknown>;")
    out.append("  /** Blocking GET on the script worker; resolves with the body. */")
    out.append("  httpGet(url: string, timeoutMs?: number): Promise<string>;")
    out.append("}")
    out.append("")
    out.append("declare const Combat: Combat;")
    out.append("declare const Render: Render;")
    out.append("declare const World: World;")
    out.append("declare const Network: Network;")
    out.append("declare const Hud: Hud;")
    out.append("declare const Perf: Perf;")
    out.append("declare const Input: Input;")
    out.append("declare const async: AsyncFacade;")
    out.append("")
    return "\n".join(out)


#----------------------------------------------------------------------------
# Luau
#----------------------------------------------------------------------------

def _luau_type(t):
    return TYPE_MAP[t][2]


def emit_luau(modules):
    out = ["-- " + BANNER.replace("// ", ""),
           "-- Luau type definitions for the BerryAPI script surface.", "",
           "export type TaskId = number", "export type WidgetId = number",
           "export type ActorHandle = { id: number }",
           "export type Vec3 = { x: number, y: number, z: number }",
           "export type Rgba = { r: number, g: number, b: number, a: number }",
           "export type HttpResult = { status: number, body: string, ok: boolean }",
           ""]
    for mod in modules:
        if not mod.functions:
            continue
        out.append("-- Capability required: %s." % mod.capability)
        out.append("export type %s = {" % mod.name)
        for fn in mod.functions:
            args = ", ".join("%s: %s" % (p.name, _luau_type(p.type)) for p in fn.params)
            ret = "()" if fn.ret == "nil" else _luau_type(fn.ret)
            if fn.doc:
                out.append("  -- %s" % fn.doc)
            out.append("  %s: (%s) -> %s," % (fn.name, args, ret))
        out.append("}")
        out.append("")
    out.append("export type AsyncFacade = {")
    out.append("  wait: (ticks: number) -> ((),")
    out.append("  eventsOnce: (channel: string) -> (unknown,")
    out.append("  httpGet: (url: string, timeoutMs: number?) -> (string,")
    out.append("}")
    out.append("")
    return "\n".join(out)


#----------------------------------------------------------------------------
# Docs
#----------------------------------------------------------------------------

def emit_docs(modules):
    out = ["<!-- " + BANNER.replace("// ", "") + " -->", "",
           "# BerryAPI script API", "",
           "Generated from `api/berry.idl`. Each function lists the capability a",
           "script must be granted before it can call it.", ""]
    for mod in modules:
        out.append("## %s" % mod.name)
        out.append("")
        out.append("Capability: `%s`." % mod.capability)
        if mod.doc:
            out.append("")
            out.append(mod.doc)
        out.append("")
        if mod.functions:
            out.append("| Function | Capability | Description |")
            out.append("| --- | --- | --- |")
            for fn in mod.functions:
                sig = "%s(%s)" % (fn.binding, ", ".join(
                    "%s: %s" % (p.name, p.type) for p in fn.params))
                out.append("| `%s -> %s` | `%s` | %s |" % (
                    sig, fn.ret, fn.capability, fn.doc or "-"))
            out.append("")
        if mod.events:
            out.append("Events (await with `Events.once`):")
            out.append("")
            for ev in mod.events:
                out.append("- `%s(%s)` — %s" % (
                    ev.channel,
                    ", ".join("%s: %s" % (p.name, p.type) for p in ev.params),
                    ev.doc or "-"))
            out.append("")
    return "\n".join(out)


def write_if_changed(path, content):
    if os.path.exists(path):
        with open(path, "r") as fh:
            if fh.read() == content:
                return False
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write(content)
    return True


SELF_TEST_CASES = [
    # (description, idl text, expect_error)
    ("minimal",
     "module A {\n capability render\n fn go() -> nil\n}\n", False),
    ("duplicate binding",
     "module A {\n capability render\n fn go() -> nil\n fn go() -> nil\n}\n", True),
    ("unknown type",
     "module A {\n capability render\n fn go(x: Bogus) -> nil\n}\n", True),
    ("untyped parameter",
     "module A {\n capability render\n fn go(x) -> nil\n}\n", True),
    ("fn outside module",
     "fn go() -> nil\n", True),
    ("unknown capability",
     "module A {\n capability teleport\n fn go() -> nil\n}\n", True),
    ("duplicate event",
     "module A {\n capability events\n event e()\n event e()\n}\n", True),
    ("event with typed param",
     "module A {\n capability events\n event e(dmg: number)\n}\n", False),
]


def self_test():
    """Prove the parser accepts good IDL and rejects the failure modes the
    build relies on. Runs as part of `make idl-check`."""
    failures = []
    for desc, text, expect_error in SELF_TEST_CASES:
        try:
            parse(text)
            got_error = False
        except IdlError:
            got_error = True
        if got_error != expect_error:
            failures.append("%s: expected %s, got %s" % (
                desc, "error" if expect_error else "ok",
                "error" if got_error else "ok"))
    # The real IDL must parse and must produce a non-empty, fail-closed table.
    try:
        modules = parse(open(IDL_PATH).read())
    except IdlError as exc:
        failures.append("api/berry.idl did not parse: %s" % exc)
        modules = []
    if not modules:
        failures.append("api/berry.idl produced no modules")
    for mod in modules:
        for fn in mod.functions:
            if fn.capability is None:
                failures.append("binding %s has no capability" % fn.binding)
    if failures:
        for f in failures:
            sys.stderr.write("idlgen self-test: %s\n" % f)
        return 1
    return 0


def main(argv):
    if "--self-test" in argv:
        return self_test()
    check = "--check" in argv
    with open(IDL_PATH, "r") as fh:
        text = fh.read()
    try:
        modules = parse(text)
    except IdlError as exc:
        sys.stderr.write("idlgen: %s\n" % exc)
        return 1

    outputs = {
        os.path.join(ROOT, "include", "berry", "generated_bindings.h"): emit_cpp(modules),
        os.path.join(ROOT, "generated", "berry.d.ts"): emit_ts(modules),
        os.path.join(ROOT, "generated", "berry.luau"): emit_luau(modules),
        os.path.join(ROOT, "docs", "API.md"): emit_docs(modules),
    }

    if check:
        stale = [p for p, c in outputs.items() if not _up_to_date(p, c)]
        if stale:
            for p in stale:
                sys.stderr.write("idlgen: stale generated file: %s\n" %
                                 os.path.relpath(p, ROOT))
            sys.stderr.write("idlgen: run `make idl`\n")
            return 1
        return 0

    for path, content in outputs.items():
        changed = write_if_changed(path, content)
        sys.stdout.write("%s %s\n" % ("updated" if changed else "unchanged",
                                      os.path.relpath(path, ROOT)))
    return 0


def _up_to_date(path, content):
    if not os.path.exists(path):
        return False
    with open(path, "r") as fh:
        return fh.read() == content


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
